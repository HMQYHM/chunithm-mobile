using System;
using System.Collections.Generic;

namespace ChunithmMobile.Input
{
    // 输入数据契约：GroundContact 和 AirState 是“采样结果”，不是判定结果。
    // 任何模块都不应在这里写入 JC/MISS；它们只记录时间、覆盖区域和运动事实。
    public enum GroundPhase { Down, Move, Up, Stationary }

    public struct GroundContact
    {
        public int PointerId;
        public GroundPhase Phase;
        public double TimeMs;
        public double StartTimeMs;
        public float LanePosition;
        public float PreviousLanePosition;
        // Normalized position inside the configured touchpad. Skin overlays use
        // this value for visual tracking; judgement continues to use lanes.
        public float SurfaceX;
        public float PreviousSurfaceX;
        public float VelocitySurfaceXPerSecond;
        public float PreviousSurfaceY;
        public float VelocitySurfaceYPerSecond;
        // Discrete cabinet lane indices. The float positions remain available
        // for visual feedback, while judgement uses these 16 zones.
        public int LaneIndex;
        public int PreviousLaneIndex;
        public float VelocityLanesPerSecond;
        public int FirstLane;
        public int LastLane;
        public ushort CoveredLaneMask;
        public ushort PressedLaneMask;
        public float TouchSize;
        // 触控点在当前触控板区域内的纵向位置，仅供皮肤分区表现使用。
        public float SurfaceY;
        public float FlickTravelLanes;
        // Simple FLICK consumes a movement pulse instead of the authored lane.
        // The pulse is generated by ArcadeTouchInput after 0.5 lane of travel.
        public bool HasFlickMove;
        public int FlickDirection;
    }

    public struct AirState
    {
        public double TimeMs;
        public bool Present;
        // Raw monotonic input timestamps. These survive empty Unity touch
        // samples so the judge can apply a short sensor-history tolerance.
        public double LastPresentTimeMs;
        public double LastMotionTimeMs;
        // Increments when the six-sensor bridge observes a new movement
        // sample. The judge uses this to distinguish a fresh AIR gesture from
        // a stale timestamp left after the hand stops moving.
        public int MotionSequence;
        public ushort ActiveSensorMask;
        public ushort MotionSensorMask;
        public ushort EnteredSensorMask;
        public ushort ExitedSensorMask;
        public int LowestSensor;
        public int HighestSensor;
        public float MeanHeight;
        public float MeanX;
        public int ContactCount;
        public float VerticalVelocity;
        public int MotionSensorDelta;
        public int MotionDirection;
        public bool HasVerticalMotion;
        public ushort RisingSensorMask;
        public ushort FallingSensorMask;
        public bool HasRisingMotion;
        public bool HasFallingMotion;
    }

    public sealed class ArcadeInputFrame
    {
        public readonly List<GroundContact> Ground = new List<GroundContact>(10);
        public AirState Air;

        public bool Covers(int lane, int width)
        {
            ushort mask = 0;
            int first = Math.Max(0, lane);
            int last = Math.Min(ArcadeTouchInput.LaneCount, lane + Math.Max(1, width));
            for (int index = first; index < last; index++) mask |= (ushort)(1 << index);
            foreach (var contact in Ground)
                if (contact.Phase != GroundPhase.Up && (contact.CoveredLaneMask & mask) != 0) return true;
            return false;
        }
    }
}
